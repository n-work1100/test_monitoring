#!/usr/bin/env python3
"""Генератор конфігурації Nagios із source of truth.

    inventory/hosts.yml  ->  nagios/etc/conf.d/generated/*.cfg

Використання:
    python tools/gen.py            # згенерувати
    python tools/gen.py --check    # нічого не писати, лише перевірити актуальність (CI)

Залежність: PyYAML  ->  python -m pip install pyyaml
"""
from __future__ import annotations

import sys
from pathlib import Path

try:
    import yaml
except ModuleNotFoundError:  # pragma: no cover
    sys.exit("Потрібен PyYAML:  python -m pip install pyyaml")

ROOT = Path(__file__).resolve().parents[1]
INVENTORY = ROOT / "inventory" / "hosts.yml"
OUTDIR = ROOT / "nagios" / "etc" / "conf.d" / "generated"

ROLES = ("switch", "camera", "nvr")

ROLE_HOST_TEMPLATE = {"switch": "switch-host", "camera": "camera-host", "nvr": "nvr-host"}
ROLE_SERVICE_TEMPLATE = {
    "switch": "generic-service",
    "camera": "camera-service",
    "nvr": "camera-service",
}
ROLE_GROUP = {"switch": "switches", "camera": "cameras", "nvr": "nvrs"}

ROLE_SERVICES = {
    "switch": [
        ("PING", "check_ping!200.0,20%!500.0,60%"),
        ("SNMP-Uptime", "check_snmp_uptime"),
        ("SNMP-IfNumber", "check_snmp_ifnumber"),
    ],
    "camera": [
        ("PING", "check_ping!200.0,20%!500.0,60%"),
        ("SNMP-Uptime", "check_snmp_uptime"),
        ("RTSP-554", "check_tcp!554"),
        ("WEB-80", "check_tcp!80"),
    ],
    "nvr": [
        ("PING", "check_ping!200.0,20%!500.0,60%"),
        ("SNMP-Uptime", "check_snmp_uptime"),
        ("RTSP-554", "check_tcp!554"),
    ],
}

HEADER = """\
# ============================================================================
# AUTOGENERATED FILE - НЕ РЕДАГУЙТЕ ВРУЧНУ
#   source of truth : inventory/hosts.yml
#   generator       : tools/gen.py
# Ручні правки буде втрачено при наступній генерації.
# ============================================================================
"""


def load_inventory() -> tuple[dict, list[dict]]:
    if not INVENTORY.is_file():
        sys.exit(f"Не знайдено {INVENTORY}")
    data = yaml.safe_load(INVENTORY.read_text(encoding="utf-8")) or {}
    defaults = data.get("defaults") or {}
    hosts = data.get("hosts") or []

    errors: list[str] = []
    seen: set[str] = set()
    result: list[dict] = []
    for idx, raw in enumerate(hosts, start=1):
        host = {**defaults, **(raw or {})}
        name = str(host.get("name", "")).strip()
        if not name:
            errors.append(f"hosts[{idx}]: відсутнє поле name")
            continue
        if name in seen:
            errors.append(f"{name}: дубльоване ім'я")
        seen.add(name)
        if not host.get("address"):
            errors.append(f"{name}: відсутнє поле address")
        role = host.get("role")
        if role not in ROLES:
            errors.append(f"{name}: role={role!r} не входить до {ROLES}")
        host["name"] = name
        result.append(host)

    if errors:
        sys.exit("Помилки в inventory/hosts.yml:\n  - " + "\n  - ".join(errors))
    return defaults, result


def is_monitored(host: dict) -> bool:
    value = host.get("monitoring", True)
    if isinstance(value, str):
        return value.strip().lower() not in ("false", "no", "0", "off")
    return bool(value)


def render_host(host: dict) -> str:
    role = host["role"]
    site = host.get("site", "lab")
    notes = str(host.get("notes", "")).replace('"', "'")
    lines = [
        "define host {",
        f"    use                     {ROLE_HOST_TEMPLATE[role]}",
        f"    host_name               {host['name']}",
        f'    alias                   {host.get("alias", host["name"])}',
        f"    address                 {host['address']}",
        f"    hostgroups              site-{site},{ROLE_GROUP[role]}",
    ]
    if notes:
        lines.append(f'    notes                   "{notes}"')
    lines.append("}")
    return "\n".join(lines)


def render_service(host: dict, description: str, command: str) -> str:
    return "\n".join(
        [
            "define service {",
            f"    use                     {ROLE_SERVICE_TEMPLATE[host['role']]}",
            f"    host_name               {host['name']}",
            f"    service_description     {description}",
            f"    check_command           {command}",
            "}",
        ]
    )


def write(path: Path, blocks: list[str], check: bool) -> bool:
    content = HEADER + "\n" + "\n\n".join(blocks) + "\n\n" if blocks else HEADER + "\n"
    old = path.read_text(encoding="utf-8") if path.is_file() else None
    changed = old != content
    if changed and not check:
        path.write_text(content, encoding="utf-8", newline="\n")
    return changed


def main() -> int:
    check = "--check" in sys.argv[1:]
    _, hosts = load_inventory()
    active = [h for h in hosts if is_monitored(h)]

    # групуємо за site
    sites: dict[str, list[dict]] = {}
    for host in active:
        sites.setdefault(str(host.get("site", "lab")), []).append(host)

    OUTDIR.mkdir(parents=True, exist_ok=True)
    changed_files: list[str] = []

    for site, site_hosts in sorted(sites.items()):
        host_blocks = [render_host(h) for h in site_hosts]
        service_blocks = [
            render_service(h, desc, cmd) for h in site_hosts for desc, cmd in ROLE_SERVICES[h["role"]]
        ]
        if write(OUTDIR / f"hosts-{site}.cfg", host_blocks, check):
            changed_files.append(f"hosts-{site}.cfg")
        if write(OUTDIR / f"services-{site}.cfg", service_blocks, check):
            changed_files.append(f"services-{site}.cfg")

    # hostgroups: по ролях (site-* створюються implicitly у host-блоках)
    groups: list[str] = []
    for role, group in ROLE_GROUP.items():
        groups.append(
            "\n".join(
                [
                    "define hostgroup {",
                    f"    hostgroup_name          {group}",
                    f"    alias                   {role.capitalize()}s",
                    "}",
                ]
            )
        )
    for site in sorted(sites):
        groups.append(
            "\n".join(
                [
                    "define hostgroup {",
                    f"    hostgroup_name          site-{site}",
                    f"    alias                   Site {site}",
                    "}",
                ]
            )
        )
    if write(OUTDIR / "groups.cfg", groups, check):
        changed_files.append("groups.cfg")

    # залежності: camera/nvr залежить від комутаторів свого site
    deps: list[str] = []
    for site, site_hosts in sorted(sites.items()):
        switches = [h["name"] for h in site_hosts if h["role"] == "switch"]
        dependents = [h["name"] for h in site_hosts if h["role"] in ("camera", "nvr")]
        for sw in switches:
            for dep in dependents:
                deps.append(
                    "\n".join(
                        [
                            f"# {dep} недоступний, якщо {sw} down -> без спаму алертів",
                            "define hostdependency {",
                            f"    host_name                       {sw}",
                            f"    dependent_host_name             {dep}",
                            "    dependency_period               24x7",
                            "    notification_failure_criteria   d,u",
                            "}",
                        ]
                    )
                )
    if write(OUTDIR / "dependencies.cfg", deps, check):
        changed_files.append("dependencies.cfg")

    if check and changed_files:
        print("Застаріла генерація: " + ", ".join(changed_files))
        return 1

    print(
        f"OK: {len(hosts)} хостів у SoT, {len(active)} моніторяться, "
        f"сайтів: {len(sites)}, файлів змінено: {len(changed_files)}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
